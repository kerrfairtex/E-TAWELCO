begin;

alter table public.bills add column if not exists amount_centavos bigint;
update public.bills set amount_centavos = round(amount * 100)::bigint where amount_centavos is null;
alter table public.bills alter column amount_centavos set not null;
alter table public.bills add constraint bills_amount_centavos_positive check (amount_centavos > 0);

alter table public.bills drop constraint if exists bills_status_check;
alter table public.bills add constraint bills_status_check check (status in ('unpaid','pending','paid','failed','expired','cancelled','refunded','overdue'));

create table if not exists public.payment_attempts (
  id bigint generated by default as identity primary key,
  bill_id bigint not null references public.bills(id) on delete restrict,
  user_id uuid not null references public.profiles(id) on delete restrict,
  amount_centavos bigint not null check (amount_centavos > 0),
  currency text not null default 'PHP' check (currency = 'PHP'),
  status text not null check (status in ('pending','paid','failed','expired','cancelled')),
  idempotency_key text not null unique,
  provider_checkout_session_id text unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  bill_id bigint not null references public.bills(id) on delete restrict,
  provider_payment_id text not null unique,
  amount_centavos bigint not null check (amount_centavos > 0),
  method text not null,
  status text not null check (status in ('paid','failed','refunded')),
  paid_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.payment_events (
  id bigint generated by default as identity primary key,
  provider_event_id text not null unique,
  type text not null,
  raw_payload jsonb not null,
  processed_at timestamptz,
  livemode boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.refunds (
  id bigint generated by default as identity primary key,
  payment_id bigint not null references public.payments(id) on delete restrict,
  provider_refund_id text not null unique,
  amount_centavos bigint not null check (amount_centavos > 0),
  status text not null check (status in ('pending','succeeded','failed')),
  created_at timestamptz not null default now()
);

create unique index if not exists payments_one_successful_per_bill_idx on public.payments (bill_id) where status = 'paid';
create index if not exists payment_attempts_bill_id_idx on public.payment_attempts (bill_id);
create index if not exists payment_attempts_user_id_idx on public.payment_attempts (user_id);
create index if not exists payments_bill_id_idx on public.payments (bill_id);
create index if not exists payment_events_type_idx on public.payment_events (type);
create index if not exists refunds_payment_id_idx on public.refunds (payment_id);
create index if not exists bills_account_no_idx on public.bills (account_no);

alter table public.bills enable row level security;
alter table public.payment_attempts enable row level security;
alter table public.payments enable row level security;
alter table public.payment_events enable row level security;
alter table public.refunds enable row level security;

drop policy if exists payment_attempts_member_select on public.payment_attempts;
create policy payment_attempts_member_select on public.payment_attempts for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists payments_member_select on public.payments;
create policy payments_member_select on public.payments for select to authenticated using (exists (select 1 from public.payment_attempts a where a.bill_id = payments.bill_id and a.user_id = (select auth.uid())));
drop policy if exists refunds_member_select on public.refunds;
create policy refunds_member_select on public.refunds for select to authenticated using (exists (select 1 from public.payments p join public.payment_attempts a on a.bill_id = p.bill_id where p.id = refunds.payment_id and a.user_id = (select auth.uid())));

revoke insert, update, delete on public.bills from anon, authenticated;
revoke insert, update, delete on public.payment_attempts, public.payments, public.payment_events, public.refunds from anon, authenticated;

commit;
